#!/usr/bin/env python3
"""Regenerates src/atc.js from atc.html. Run after editing atc.html."""
import json, pathlib
here = pathlib.Path(__file__).parent
html = (here / "atc.html").read_text()
(here / "src" / "atc.js").write_text("// GENERATED by build.py from atc.html - edit atc.html instead.\nexport default " + json.dumps(html) + ";\n")
print("src/atc.js written,", len(html), "bytes")
