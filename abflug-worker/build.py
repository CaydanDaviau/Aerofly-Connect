#!/usr/bin/env python3
"""Regenerates src/atc.js and src/map.js from atc.html and map.html. Run after editing either."""
import json, pathlib
here = pathlib.Path(__file__).parent
for name in ("atc", "map"):
    html = (here / (name + ".html")).read_text()
    (here / "src" / (name + ".js")).write_text("// GENERATED by build.py from " + name + ".html - edit the .html instead.\nexport default " + json.dumps(html) + ";\n")
    print("src/" + name + ".js written,", len(html), "bytes")
